function contentStreams(file: string): string[] {
  const raw = fs.readFileSync(file).toString('latin1');
  return [...raw.matchAll(/stream\n([\s\S]*?)\nendstream/g)].map(([, stream]) => zlib.inflateSync(Buffer.from(stream, 'latin1')).toString('latin1'));
}

// Text of each BT…ET block in drawing order. The standard fonts encode text as WinAnsi hex strings.
// WinAnsi bytes 0x80-0x9F. Node 20's TextDecoder('windows-1252') decodes these as C1 control characters.
const WIN_ANSI_80_9F = '€\x81‚ƒ„…†‡ˆ‰Š‹Œ\x8DŽ\x8F\x90‘’“”•–—˜™š›œ\x9DžŸ';
const winAnsi = (bytes: Buffer) => [...bytes].map(b => (b >= 0x80 && b < 0xa0 ? WIN_ANSI_80_9F[b - 0x80] : String.fromCharCode(b))).join('');

function pdfLines(file: string): string[] {
  return contentStreams(file).flatMap(content => [...content.matchAll(/\bBT\b[\s\S]*?\bET\b/g)].map(([block]) =>
    [...block.matchAll(/<([0-9a-f]+)>/gi)].map(([, hex]) => winAnsi(Buffer.from(hex, 'hex'))).join('')));
}

function expectDrawn(lines: string[], run: unknown[]): void {
  const at = lines.indexOf(run[0] as string);
  expect(lines.slice(at, at + run.length)).toEqual(run);
}

const pages = (lines: string[]) => lines.filter(l => /^Page \d+  ·  /.test(l)).map(l => l.split('  ·  ')[0]);

const FOOTER = expect.stringMatching(/^Generated by playwright-smart-reporter v\d/);

function rectFill(content: string, rect: string): string | undefined {
  const rgb = content.match(new RegExp(`\\n${rect.replace(/\./g, '\\.')} re\\n/DeviceRGB cs\\n([\\d. ]+) scn\\nf\\n`))?.[1];
  return rgb && '#' + rgb.split(' ').map(v => Math.round(Number(v) * 255).toString(16).padStart(2, '0')).join('');
}

// Fill colour of each drawn text equal to `text`: the last colour set before it.
function textColors(content: string, text: string): string[] {
  const hex = `<${Buffer.from(text, 'latin1').toString('hex')}>`;
  const colors: string[] = [];
  for (let at = content.indexOf(hex); at >= 0; at = content.indexOf(hex, at + 1)) {
    const rgb = [...content.slice(0, at).matchAll(/([\d.]+ [\d.]+ [\d.]+) scn/g)].at(-1)![1];
    colors.push('#' + rgb.split(' ').map(v => Math.round(Number(v) * 255).toString(16).padStart(2, '0')).join(''));
  }
  return colors;
}

// Segment count of each stroked polyline with 2+ segments: the trend sparklines.
const sparklines = (content: string) => (content.match(/ m\n(?:[\d.-]+ [\d.-]+ l\n){2,}S\n/g) ?? []).map(p => p.split(' l\n').length - 1);

const baseFonts = (file: string) => [...new Set(fs.readFileSync(file).toString('latin1').match(/\/BaseFont \/\S+/g)!.map(f => f.replace(/^\/BaseFont \/([A-Z]{6}\+)?/, '')))];

function createTestResult(overrides: Partial<TestResultData> = {}): TestResultData {
  return {
    testId: 'test-1',
    title: 'Test One',
    file: 'tests/example.spec.ts',
    status: 'passed',
    duration: 1000,
    retry: 0,
    steps: [],
    history: [],
    ...overrides,
  };
}

function createTestHistory(overrides: Partial<TestHistory> = {}): TestHistory {
  return {
    runs: [],
    tests: {},
    summaries: [],
    ...overrides,
  };
}

function createRunSummary(overrides: Partial<RunSummary> = {}): RunSummary {
  return {
    runId: 'run-1',
    timestamp: new Date().toISOString(),
    total: 10,
    passed: 8,
    failed: 2,
    skipped: 0,
    flaky: 1,
    slow: 1,
    duration: 5000,
    passRate: 80,
    ...overrides,
  };
}

function createStabilityScore(overrides: Partial<StabilityScore> = {}): StabilityScore {
  return {
    overall: 90,
    flakiness: 95,
    performance: 85,
    reliability: 90,
    grade: 'A',
    needsAttention: false,
    ...overrides,
  };
}

function createBasicData(overrides: Partial<ExecutivePdfData> = {}): ExecutivePdfData {
  return {
    results: [createTestResult()],
    history: createTestHistory(),
    startTime: Date.now() - 5000,
    ...overrides,
  };
}

